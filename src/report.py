def _find_pandoc():
    """Ищет pandoc: в PATH, затем в типовых местах установки Windows."""
    import shutil

    found = shutil.which("pandoc")
    if found:
        return found
    candidates = [
        os.path.expandvars(r"%LOCALAPPDATA%\Pandoc\pandoc.exe"),
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\Pandoc\pandoc.exe"),
        r"C:\Program Files\Pandoc\pandoc.exe",
        r"C:\Program Files (x86)\Pandoc\pandoc.exe",
    ]
    for cand in candidates:
        if os.path.exists(cand):
            return cand
    return "pandoc"


def export_pdf(md_path, output_dir="docs"):
    """Экспортирует Markdown-отчёт в PDF через pandoc (движок typst)."""
    pdf_path = os.path.join(output_dir, "report.pdf")
    if os.path.exists(pdf_path):
        os.remove(pdf_path)
    env = os.environ.copy()
    extra = ""
    try:
        import winreg

        for scope in ("Machine", "User"):
            hive = winreg.HKEY_LOCAL_MACHINE if scope == "Machine" else winreg.HKEY_CURRENT_USER
            try:
                key = winreg.OpenKey(hive, "Environment")
                try:
                    value, _ = winreg.QueryValueEx(key, "Path")
                    extra += ";" + value
                finally:
                    winreg.CloseKey(key)
            except OSError:
                continue
    except ImportError:
        pass
    env["PATH"] = extra + ";" + env.get("PATH", "")
    pandoc = _find_pandoc()
    cmd = [
        pandoc,
        md_path,
        "-o",
        pdf_path,
        "--pdf-engine=typst",
        "--toc",
        "--resource-path=" + output_dir,
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, env=env, check=False)
    if not os.path.exists(pdf_path):
        raise RuntimeError(f"Экспорт PDF не удался: {result.stderr}")
    return pdf_path


# END: export_pdf
